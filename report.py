"""Turn a results dict from run_matrix.py into the Markdown tables in results.md."""

from __future__ import annotations

from expected import ABLATIONS, BLOCKED_BY, EXPECTED, LEVELS

LEVEL_NAMES = [column.name for column in LEVELS]
Cells = dict[tuple[str, str], dict]


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def shown(cell: dict) -> str:
    text = cell["error"] if cell["outcome"] == "blocked" else cell["outcome"]
    return text + (" **FAIL**" if cell["problems"] else "")


def matrix_rows(
    cells: Cells, columns: list[str], attacks: list[str]
) -> list[list[str]]:
    return [[attack, *(shown(cells[c, attack]) for c in columns)] for attack in attacks]


def first_blocked_rows(cells: Cells) -> list[list[str]]:
    rows = []
    for attack in EXPECTED:
        outcomes = [cells[name, attack] for name in LEVEL_NAMES]
        levels = [n for n, cell in enumerate(outcomes) if cell["outcome"] == "blocked"]
        if not levels:
            continue
        first = levels[0]
        if first == 0:
            before = "blocked at L0: it never works here"
        else:
            before = f"{outcomes[first - 1]['outcome']} at L{first - 1}"
        rows.append(
            [attack, f"L{first}", outcomes[first]["error"], BLOCKED_BY[first], before]
        )
    return rows


def ablation_rows(cells: Cells) -> list[list[str]]:
    """Only the attacks where an ablation differs from the level it is compared with."""

    def result(column: str, attack: str) -> tuple:
        return cells[column, attack]["outcome"], cells[column, attack]["error"]

    rows = []
    for attack in EXPECTED:
        differs = any(
            result(column.name, attack) != result(f"L{column.like_level}", attack)
            for column in ABLATIONS
        )
        if differs:
            row = [attack]
            for column in ABLATIONS:
                row += [
                    shown(cells[f"L{column.like_level}", attack]),
                    shown(cells[column.name, attack]),
                ]
            rows.append(row)
    return rows


def timing_rows(timing: dict) -> list[list[str]]:
    floor = timing["targets"]["L0"]["median_ms"]
    rows = []
    for name, stats in timing["targets"].items():
        over_floor = f"{stats['median_ms'] - floor:+.1f}" if name != "exec only" else ""
        keys = ("median_ms", "p25_ms", "p75_ms", "min_ms", "max_ms")
        rows.append([name, *(f"{stats[key]:.1f}" for key in keys), over_floor])
    return rows


def markdown(report: dict) -> str:
    cells = {(cell["column"], cell["attack"]): cell for cell in report["runs"][0]}
    env, timing = report["environment"], report["timing"]
    attacks = [a for a in EXPECTED if not a.startswith(("ctl_", "gap_"))]
    controls = [a for a in EXPECTED if a.startswith("ctl_")]
    gaps = [a for a in EXPECTED if a.startswith("gap_")]
    ablation_header = ["attack"]
    for column in ABLATIONS:
        ablation_header += [f"L{column.like_level}", column.name]

    parts = [
        "# Agent sandbox: attack matrix",
        f"Generated by `run_matrix.py`. Kernel {env['kernel']} on {env['machine']}, "
        f"Python {env['python']}, Landlock ABI {env['landlock_abi']}.",
        f"The matrix ran {report['matrix_runs']} times, {report['cells_per_run']} cells "
        f"each. Cells that missed the expected table: {report['failed_cells']}. "
        f"Runs identical: {'yes' if report['runs_identical'] else 'NO'}. "
        f"Sandbox state left behind: {report['leftover_sandbox_state'] or 'none'}.",
        "## Attacks",
        "A cell shows `allowed`, `n/a` (below L5 there is no proxy to ask), or the "
        "error that stopped the attack.",
        table(["attack", *LEVEL_NAMES], matrix_rows(cells, LEVEL_NAMES, attacks)),
        "## Where each attack is first blocked",
        table(
            ["attack", "first blocked", "error", "blocked by", "one level earlier"],
            first_blocked_rows(cells),
        ),
        "## Positive controls",
        "These must keep working at every level where they apply.",
        table(["control", *LEVEL_NAMES], matrix_rows(cells, LEVEL_NAMES, controls)),
        "## Known gaps",
        "Attacks that no layer in this sandbox stops.",
        table(["attack", *LEVEL_NAMES], matrix_rows(cells, LEVEL_NAMES, gaps)),
        "## Ablations",
        "`filter-only` is no_new_privs and seccomp with no namespaces, next to L0. "
        "`landlock-only` is Landlock with no namespaces, next to L0. "
        "`L5-no-address-check` is L5 with an empty denied-network list, next to L5. "
        "Only the attacks where an ablation changes the result are listed.",
        table(ablation_header, ablation_rows(cells)),
        "## Seccomp filter coverage",
        "Every denied syscall, called with all-zero arguments one level below the "
        "filter and at the filter's level.",
        table(
            ["syscall", "errno at L2", "errno at L3", "verdict"],
            [
                [row["syscall"], row["without"], row["with_filter"], row["verdict"]]
                for row in report["syscall_coverage"]
            ],
        ),
        "## Start-up time",
        "Wall time in milliseconds of one whole `python3 sandbox.py --level N -- "
        "/bin/true` process, measured by its parent from spawn to exit. It includes "
        "the interpreter start, the imports, the layer setup, the command and the "
        "teardown. `exec only` is `/bin/true` with no sandbox.py at all. "
        f"{timing['runs_per_target']} runs per row after "
        f"{timing['warm_up_runs_discarded']} discarded warm-up runs, with the rows "
        f"interleaved. Runs that failed: {timing['failed_runs']}. "
        f"{timing['cpus']} CPUs. Load average {timing['load_average_before']:.2f} "
        f"before, {timing['load_average_after']:.2f} after.",
        table(
            ["target", "median", "p25", "p75", "min", "max", "median minus L0"],
            timing_rows(timing),
        ),
    ]
    return "\n\n".join(parts) + "\n"
